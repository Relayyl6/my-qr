/**
 * Vector SVG QR Code generator and exporter
 * Generates standards-compliant SVG with clean path tags for Figma, Illustrator & laser cutters.
 */

export function downloadSvgFile(filename: string, svgContent: string) {
  const blob = new Blob([svgContent], { type: "image/svg+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename.endsWith(".svg") ? filename : `${filename}.svg`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Extracts and enhances the SVG markup from a rendered SVG element
 */
export function extractCleanSvgMarkup(svgElement: SVGElement, title?: string, url?: string): string {
  const cloned = svgElement.cloneNode(true) as SVGElement;
  cloned.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  cloned.setAttribute("version", "1.1");

  if (title) {
    const titleTag = document.createElementNS("http://www.w3.org/2000/svg", "title");
    titleTag.textContent = title;
    cloned.insertBefore(titleTag, cloned.firstChild);
  }

  if (url) {
    const descTag = document.createElementNS("http://www.w3.org/2000/svg", "desc");
    descTag.textContent = `Generated by DynamicQR • Redirects to ${url}`;
    cloned.appendChild(descTag);
  }

  return cloned.outerHTML;
}
